"""Paired redirect / callback handler factory for OAuthClientProvider.

The SDK's ``OAuthClientProvider._perform_authorization_code_grant``
calls ``redirect_handler(authorization_url)`` and then
``callback_handler() -> tuple[code, returned_state]``. The two halves
are separated by a yield boundary inside ``async_auth_flow`` and the
operator's IDP consent round-trip; the ``state`` token that links
them is generated by the SDK *inside* ``_perform_authorization`` and
only surfaces to user code via the ``authorization_url`` argument
passed to ``redirect_handler``.

A stand-alone ``make_callback_handler(state)`` factory cannot work
because the state is not known at handler-construction time; it
emerges from the redirect URL. The paired-factory pattern below
constructs both handlers atomically, sharing a closure-private
``state_box: asyncio.Future[str]`` that ``redirect_handler`` resolves
and ``callback_handler`` awaits.

Async-context constraint (cycle-2 NEW-M1): ``make_oauth_handlers``
calls ``asyncio.get_running_loop().create_future()`` synchronously,
which raises ``RuntimeError: no running event loop`` when called
outside an async context. Production usage is fine — L4's
``connect_streamable_http`` calls this from inside an async tool-
invocation path. Tests MUST construct handlers inside ``async def
test_...`` bodies; synchronous fixtures cannot construct them.

Synthetic chat-session-id pattern. Three csid shapes pass through
this module's ``redirect_handler`` closure: real csids (12-char uuid4
hex, allocated per chat WebSocket connection by
``the_one.interfaces.web.app``), ``f"test:{source_id}"`` (allocated by
the F6.5 Test connection endpoint at
``the_one/interfaces/web/api.py:~867,~912`` when no chat WS
subscription exists), and ``f"agent_build:{source.id}"`` (allocated by
``_pool._entry_worker`` at ``the_one/mcp/_pool.py:200`` when an
OAuth-token-bearing source is connected outside a chat path —
REST/CLI/agent-build). The two namespaces are disjoint by
**character-set construction**: real csids are 12-char lowercase hex
(charset ``[0-9a-f]``); synthetic csids contain a literal ``:``
separator that the hex charset cannot produce. Collision is impossible
regardless of the synthetic-prefix length. The redirect_handler's
``_sessions.get(synthetic_csid)`` lookup returns None for both
synthetic shapes, so the ``auth_required`` broadcast becomes a guarded
no-op — appropriate, since neither path has a chat UI to surface a
modal.
"""

from __future__ import annotations

import asyncio
from collections.abc import Awaitable, Callable
from urllib.parse import parse_qs, urlsplit

from mcp.client.auth.exceptions import OAuthFlowError

from the_one.mcp.oauth import _state


def make_oauth_handlers(
    chat_session_id: str,
    source_id: str,
    tool_call_id: str | None,
    resource_metadata_url: str | None,
    *,
    consent_url_future: asyncio.Future[str] | None = None,
) -> tuple[
    Callable[[str], Awaitable[None]],
    Callable[[], Awaitable[tuple[str, str | None]]],
]:
    """Construct a paired ``(redirect_handler, callback_handler)`` for one
    OAuth flow.

    Both returned callables close over ``(chat_session_id, source_id,
    tool_call_id, resource_metadata_url)`` and a shared
    ``state_box: asyncio.Future[str]`` (the state token, NOT the auth
    code future). The redirect resolves ``state_box`` after registering
    via ``_state.register``; the callback awaits ``state_box`` to learn
    the state, then awaits the per-state ``code_future`` from ``_state``.

    Closure-capture invariant (cycle-2 M5): each call to this factory
    yields independent closures — five concurrent flows can register
    five state tokens with no aliasing.

    The redirect broadcasts an ``auth_required`` event to the chat
    session keyed by ``chat_session_id``. The lookup is lazy
    (``from the_one.interfaces.web.app import _sessions, _send_to_session``
    inside the handler body) to avoid the ``api.py ↔ app.py`` circular
    import at module-load time.

    When ``consent_url_future`` is supplied, the redirect_handler resolves
    it with the authorization_url AFTER registering the state token
    (preserving the register-BEFORE-resolve invariant from the existing
    closure-capture contract). The Test connection endpoint (F6.5 L3)
    supplies this future and awaits it to surface the consent_url to the
    source-edit UI without requiring a chat WebSocket subscription.
    """

    state_box: asyncio.Future[str] = asyncio.get_running_loop().create_future()

    async def redirect_handler(authorization_url: str) -> None:
        """SDK-provided callback. Parse state, register, broadcast."""
        qs = parse_qs(urlsplit(authorization_url).query)
        states = qs.get("state", [])
        state = states[0] if states else None
        if not state:
            raise OAuthFlowError("Authorization URL missing state parameter")
        # Register BEFORE resolving state_box so the callback handler
        # can _state.peek immediately upon awaiting.
        _state.register(
            state,
            source_id=source_id,
            tool_call_id=tool_call_id,
            chat_session_id=chat_session_id,
        )
        if not state_box.done():
            state_box.set_result(state)
        # F6.5 L3: surface authorization_url to the test-connection endpoint
        # if the caller supplied a future (test path); production chat path
        # passes None and falls through to the WebSocket broadcast below.
        # Guard `done()` defensively — SDK retries could call redirect twice.
        if consent_url_future is not None and not consent_url_future.done():
            consent_url_future.set_result(authorization_url)
        # Lazy import — see module docstring.
        from the_one.interfaces.web.app import _send_to_session, _sessions

        session = _sessions.get(chat_session_id)
        if session is not None:
            await _send_to_session(
                session,
                {
                    "type": "auth_required",
                    "source_id": source_id,
                    "resource_metadata_url": resource_metadata_url,
                    "tool_call_id": tool_call_id,
                    "consent_url": authorization_url,
                },
            )

    async def callback_handler() -> tuple[str, str | None]:
        """SDK-provided callback. Await state, then await code."""
        state = await state_box
        entry = _state.peek(state)
        if entry is None:
            # The redirect handler registered, but the entry was popped
            # before the callback awaited (e.g. by a TTL sweep racing
            # the IDP redirect). Surface as OAuthFlowError so the
            # SDK's auth flow re-raises into our error layer.
            raise OAuthFlowError("Pending OAuth flow not registered or already expired")
        return await entry.code_future

    return redirect_handler, callback_handler
