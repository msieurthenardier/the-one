"""The embedding seam (M24 F02 L03, DD-1): a structural Protocol, one
production backend, one test-only backend, loaded at most once per process.

``the_one/embeddings/data/`` holds the bundled float16 ``potion-retrieval-32M``
weights as package data; this package is now where the seam that loads them
lives too (Flight 1 shipped only the packaged directory and a note that "no
seam lives here" — Flight 2 designs the API this docstring now describes).

**Three places must agree** on the packaged model directory: ``pyproject.toml``'s
package-data glob, the ``collect_data_files`` entry in
``packaging/windows/the-one.spec``, and ``the_one.embeddings.local.EMBEDDING_MODEL_DIRNAME``.
It is named once, in ``local.py``.

``get_embedding_backend()`` returns a process-wide singleton (currently always
a ``LocalStaticBackend`` — the ``knowledge.embedding`` setting has exactly one
valid value per DD-2, so there is no dispatch yet; a future second bundled
model would add one here). ``warm_up()`` loads it eagerly and is called from
the web app's lifespan (gated on at least one knowledge base existing) and
from ``create_knowledge_base`` (so an operator's first KB after a cold start
doesn't pay the load inside their first indexing request either). Both call
sites are fire-and-forget — ``warm_up()`` is idempotent and swallows a loader
failure into a log line so it never fails startup or a request.

The weights are regenerated by ``make refresh-embedding-model``
(``scripts/refresh_embedding_model.py``), never edited by hand.
"""

from __future__ import annotations

import asyncio
import logging
import threading

from the_one.embeddings._backend import (
    NORM_TOLERANCE,
    EmbeddingBackend,
    EmbeddingModelMissingError,
    EmbedResult,
)
from the_one.embeddings.local import LocalStaticBackend

__all__ = [
    "NORM_TOLERANCE",
    "EmbedResult",
    "EmbeddingBackend",
    "EmbeddingModelMissingError",
    "LocalStaticBackend",
    "get_embedding_backend",
    "warm_up",
]

logger = logging.getLogger(__name__)

_backend: EmbeddingBackend | None = None
_lock = threading.Lock()
_warming = False


def get_embedding_backend() -> EmbeddingBackend:
    """Return the process-wide embedding backend, building it on first call.

    Double-checked under ``_lock`` so two concurrent first calls (e.g. two
    ``asyncio.to_thread`` workers racing at warm-up) still build the model
    exactly once. The ``knowledge.embedding`` setting has exactly one valid
    value today (DD-2) — a future second backend would dispatch here.
    """
    global _backend
    if _backend is not None:
        return _backend
    with _lock:
        if _backend is None:
            _backend = LocalStaticBackend.load()
        return _backend


async def warm_up() -> None:
    """Load the embedding backend eagerly, off the event loop.

    Idempotent and safe to call from multiple call sites (lifespan startup
    and ``create_knowledge_base``) without bookkeeping: a no-op once
    ``_backend`` is set, and re-entrant-safe against a concurrent in-flight
    warm-up via the ``_warming`` guard. A loader failure is logged, never
    raised — startup and KB creation must not fail on it; the next
    ``get_embedding_backend()`` call will raise to ITS caller instead.
    """
    global _warming
    if _backend is not None or _warming:
        return
    _warming = True
    try:
        await asyncio.to_thread(get_embedding_backend)
    except Exception:
        logger.exception("embedding backend warm-up failed")
    finally:
        _warming = False


def _reset_for_test() -> None:
    """Clear the singleton and warm-up state — for tests only.

    Mirrors ``the_one/platform/sandbox/factory.py``'s
    ``_reset_selection_log_state``. Without this a test that monkeypatches
    the loader after an earlier test has already built the singleton would
    silently observe the stale instance.
    """
    global _backend, _warming
    _backend = None
    _warming = False
