def test_testids_in_source_are_registered() -> None:
    """Every testid defined in the JS sources must appear in the registry
    (literal table for literals — manual-exceptions table also counts —
    and parametric table for prefix families).  Fails with the exact list
    to ADD to ``docs/ui-testid-registry.md``."""
    assert REGISTRY_DOC.exists(), f"Missing registry doc: {REGISTRY_DOC}"
    literals, parametric, _ = extract_testids()
    reg_literals, reg_prefixes, reg_manual = parse_registry()
    registered_literals = set(reg_literals) | set(reg_manual)
    registered_prefixes = set(reg_prefixes)

    unregistered_literals = set(literals) - registered_literals
    unregistered_prefixes = set(parametric) - registered_prefixes

    lines: list[str] = []
    if unregistered_literals:
        lines.append("Literal testids defined in source but MISSING from the registry")
        lines.append(f"(add rows to the 'Literal testids' table in {REGISTRY_DOC.name}):")
        for testid in sorted(unregistered_literals):
            files = ", ".join(sorted(literals[testid]))
            lines.append(f"  {testid}  (defined in: {files})")
    if unregistered_prefixes:
        lines.append("Parametric prefixes built in source but MISSING from the registry")
        lines.append(
            f"(add rows to the 'Parametric prefix families' table in {REGISTRY_DOC.name}):"
        )
        for prefix in sorted(unregistered_prefixes):
            files = ", ".join(sorted(parametric[prefix]))
            lines.append(f"  {prefix}  (built in: {files})")
    if lines:
        raise AssertionError("\n".join(lines))


def test_registered_testids_exist_in_source() -> None:
    """Every registry row must correspond to a real definition in the JS
    sources (reverse direction).  Also enforces that each id appears in
    the registry exactly once.  Fails with the exact list to REMOVE."""
    literals, parametric, _ = extract_testids()
    reg_literals, reg_prefixes, reg_manual = parse_registry()

    lines: list[str] = []
    all_rows = reg_literals + reg_prefixes + reg_manual
    duplicates = sorted(row for row, n in Counter(all_rows).items() if n > 1)
    if duplicates:
        lines.append(f"Registry rows appearing more than once in {REGISTRY_DOC.name}:")
        lines.extend(f"  {row}" for row in duplicates)

    stale_literals = set(reg_literals) - set(literals)
    stale_prefixes = set(reg_prefixes) - set(parametric)
    if stale_literals:
        lines.append("Registered literal testids with no definition in source")
        lines.append(f"(remove rows from {REGISTRY_DOC.name}, or restore the JS):")
        lines.extend(f"  {testid}" for testid in sorted(stale_literals))
    if stale_prefixes:
        lines.append("Registered parametric prefixes with no concatenation site in source")
        lines.append(f"(remove rows from {REGISTRY_DOC.name}, or restore the JS):")
        lines.extend(f"  {prefix}" for prefix in sorted(stale_prefixes))
    if lines:
        raise AssertionError("\n".join(lines))


def test_manual_exception_testids_still_in_source() -> None:
    """Manual-exception ids (variable-carried, invisible to extraction)
    must still appear as plain string literals somewhere in the JS
    sources, so deleting one is caught.

    The table itself may legitimately be empty (e.g. after Mission 23
    Flight 1 removed the connector editor, its sole occupants) — an empty
    list here is not evidence of a broken parser, unlike the literal/
    parametric tables which always carry entries.
    """
    _, _, reg_manual = parse_registry()
    missing = [t for t in reg_manual if not id_appears_as_string_literal(t)]
    if missing:
        raise AssertionError(
            "Manual-exception testids no longer present as string literals in "
            f"{JS_DIR}:\n" + "\n".join(f"  {t}" for t in missing)
        )


def test_selector_referenced_testids_are_defined() -> None:
    """Ids referenced via ``[data-testid="..."]`` selectors must be
    defined somewhere (literal, parametric family, or manual exception).
    A selector with no definition is a dead query — surfaced here as a
    distinct failure so it can be dispositioned explicitly."""
    literals, parametric, selector_refs = extract_testids()
    _, _, reg_manual = parse_registry()
    defined = set(literals) | set(reg_manual)
    prefixes = tuple(parametric)

    dead = {
        ref for ref in selector_refs if ref not in defined and not ref.startswith(prefixes)
    } - KNOWN_DEAD_SELECTORS
    if dead:
        lines = [
            "Selector-referenced testids with no definition in source (dead queries —",
            "fix the JS or disposition into KNOWN_DEAD_SELECTORS with a comment):",
        ]
        for ref in sorted(dead):
            files = ", ".join(sorted(selector_refs[ref]))
            lines.append(f"  {ref}  (queried in: {files})")
        raise AssertionError("\n".join(lines))


def test_design_token_mirror_in_sync() -> None:
    """Every value in the ``design_tokens.py`` mirror must match its
    ``tokens.css`` definition (top-level theme blocks only; @media
    redefinitions stripped).  Mirror-driven: mirror keys are converted
    ``snake_case`` → ``--kebab-case`` and looked up in the parsed CSS;
    values compare hex-normalized and case-insensitive.  Fails with the
    exact token/value pairs that drifted."""
    css_blocks = parse_tokens_css_theme_blocks()

    lines: list[str] = []
    for theme, mirror in (("dark", DARK), ("light", LIGHT)):
        css = css_blocks[theme]
        for key, mirror_value in mirror.items():
            css_name = "--" + key.replace("_", "-")
            if css_name not in css:
                lines.append(
                    f"  [{theme}] {css_name}: in mirror ({mirror_value!r}) but NOT defined "
                    f"in the top-level theme block"
                )
                continue
            css_value = css[css_name]
            if normalize_css_color(css_value) != normalize_css_color(mirror_value):
                lines.append(f"  [{theme}] {css_name}: mirror={mirror_value!r} css={css_value!r}")
    if lines:
        raise AssertionError(
            f"design_tokens.py mirror out of sync with {TOKENS_CSS.name} "
            "(mission 17 flight 2 lockstep contract).\n"
            "Update tests/browser/design_tokens.py (or tokens.css) so the pairs match:\n"
            + "\n".join(lines)
        )


# ── Banned-token guard (M17 F2 L3) ──────────────────────────────────────────
#
# Per-file allowance for ``clip-path: polygon`` occurrences. Emptied in
# M17 F3 L1: the last consciously-deferred chamfer remnant (the
# selected-tab L-bracket ``::before`` in components.css) was deleted with
# the tabs rebuild, so ``static/css`` now tolerates ZERO occurrences.
# Mechanism retained: COUNT-anchored, exact in both directions — any
# future entry fail-stales when its remnant goes.
CLIP_PATH_POLYGON_ALLOWANCE: dict[str, int] = {}


def test_no_retired_design_vocabulary_in_css() -> None:
    """No retired alien-console vocabulary (M17 F2) may reappear in
    ``static/css`` — glow/glass/bezel/shell/btn-v3/panel-shadow token
    names, ``backdrop-filter``, chamfer ``clip-path: polygon`` geometry
    (minus the documented per-file allowance), and
    ``prefers-reduced-transparency``. Comments count as hits. This is
    the enforcement behind SC1's retirement: without it, later flights
    could silently reintroduce the effects. Fails naming file+line."""
    hits = find_banned_css_vocabulary()

    seen_clip_path: Counter[str] = Counter()
    violations: list[str] = []
    for rel, lineno, label, line in hits:
        if label == "clip-path: polygon" and rel in CLIP_PATH_POLYGON_ALLOWANCE:
            seen_clip_path[rel] += 1
            if seen_clip_path[rel] <= CLIP_PATH_POLYGON_ALLOWANCE[rel]:
                continue
        violations.append(f"  {rel}:{lineno}: [{label}] {line}")

    lines: list[str] = []
    if violations:
        lines.append("Retired design vocabulary found in static/css (M17 F2 banned-token guard).")
        lines.append("Remove the occurrences — the v3 quiet language does not use them:")
        lines.extend(violations)
    for rel, expected in CLIP_PATH_POLYGON_ALLOWANCE.items():
        if seen_clip_path[rel] < expected:
            lines.append(
                f"Stale allowance: CLIP_PATH_POLYGON_ALLOWANCE expects {expected} "
                f"'clip-path: polygon' occurrence(s) in {rel} but found "
                f"{seen_clip_path[rel]} — the deferred remnant was removed; "
                "delete/ratchet the allowance entry."
            )
    if lines:
        raise AssertionError("\n".join(lines))


def test_no_backtick_testids_or_html_sink_payloads() -> None:
    """Backtick tripwire (M17 F2 L3, debrief rec 3): template literals
    carrying ``data-testid`` and backtick payloads feeding
    ``innerHTML``/``outerHTML``/``insertAdjacentHTML`` are banned in
    ``static/js``. The testid extractor and sink classifier above are
    calibrated for single-quoted JS strings — a backtick-quoted testid
    or sink payload would be INVISIBLE to them, silently holing the
    regression net. Comments scan like live code (write 'data-testid'
    with quotes in comments). Fails naming file+line."""
    hits = find_backtick_tripwire_hits()
    if hits:
        lines = [
            "Backtick tripwire (M17 F2): backtick-quoted testids / template-literal",
            "HTML-sink payloads found in static/js. Use single-quoted strings (the",
            "guard extractors cannot see inside template literals):",
        ]
        lines.extend(f"  {rel}:{lineno}: [{kind}] {excerpt}" for rel, lineno, kind, excerpt in hits)
        raise AssertionError("\n".join(lines))


def test_no_new_dynamic_innerhtml_sinks() -> None:
    """No NEW dynamic ``innerHTML``/``outerHTML``/``insertAdjacentHTML``
    site may appear beyond the frozen baseline.  Snippet-level multiset
    match per file: catches new files, new sites in known files, and
    offsetting add+remove.  Site removals never fail (the ratchet only
    tightens)."""
    dynamic, _ = classify_sinks()

    lines: list[str] = []
    for rel in sorted(dynamic):
        if rel not in DYNAMIC_SINK_BASELINE:
            lines.append(f"NEW file with dynamic sink(s): {rel}")
            lines.extend(f"    {s}" for s in dynamic[rel])
            continue
        baseline = Counter(DYNAMIC_SINK_BASELINE[rel])
        live = Counter(dynamic[rel])
        novel = live - baseline
        if novel:
            lines.append(f"NEW dynamic sink site(s) in {rel}:")
            for snippet, n in sorted(novel.items()):
                suffix = f"  (x{n})" if n > 1 else ""
                lines.append(f"    {snippet}{suffix}")
    if lines:
        raise AssertionError(
            "Dynamic innerHTML-sink baseline freeze violated (mission 17 flight 1).\n"
            "Render via createElement/textContent or a static template instead of\n"
            "adding a dynamic sink. Sites found beyond baseline:\n" + "\n".join(lines)
        )


