#!/usr/bin/env bash
# Userland (no sudo) host libraries for Playwright's WebKit build on Debian/Ubuntu.
#
# `playwright install-deps webkit` needs root. This downloads the missing .deb
# packages with `apt-get download` (works unprivileged) and unpacks them with
# `dpkg -x` into a cache directory OUTSIDE the repo. Idempotent: re-running skips
# packages already unpacked. tests/browser/_ui_engines.py discovers the directory
# through THE_ONE_WEBKIT_DEPS (default ~/.cache/the-one-webkit-deps) and applies
# GST_PLUGIN_PATH to the WebKit launch ONLY, and launches the browser through the
# wrapper this script writes (webkit-wrapper.sh): Playwright's bundled MiniBrowser
# wrapper OVERWRITES LD_LIBRARY_PATH, so the userland library dir cannot be passed
# through the launch env; the wrapper re-states the bundle's own paths and appends
# the userland dir. Chromium never sees any of it.
#
#   bash scripts/setup-webkit-userland.sh
#   .venv/bin/python -m playwright install webkit        # the browser itself
set -euo pipefail

DEPS_DIR="${THE_ONE_WEBKIT_DEPS:-$HOME/.cache/the-one-webkit-deps}"
PACKAGES=(
  libwoff1 libavif16 libevent-2.1-7t64 libflite1 libgtk-4-1
  libgstreamer-plugins-bad1.0-0 gstreamer1.0-plugins-bad gstreamer1.0-libav
  libgav1-1 libyuv0 libabsl20220623t64
)
# Extra packages pulled in when a first pass still leaves libraries unresolved.
PACKAGES+=(${THE_ONE_WEBKIT_EXTRA_PACKAGES:-})

mkdir -p "$DEPS_DIR/debs" "$DEPS_DIR/root"
cd "$DEPS_DIR/debs"
for pkg in "${PACKAGES[@]}"; do
  marker="$DEPS_DIR/root/.done-$pkg"
  if [ -f "$marker" ]; then
    continue
  fi
  echo "fetching $pkg"
  apt-get download "$pkg" >/dev/null
  deb="$(ls -t "${pkg}"_*.deb | head -1)"
  dpkg -x "$deb" "$DEPS_DIR/root"
  touch "$marker"
done

LIBDIRS="$(find "$DEPS_DIR/root" -type d \( -path '*/lib/*-linux-gnu' -o -path '*/usr/lib/*-linux-gnu' \) | sort -u | tr '\n' ':')"
GST_DIR="$(find "$DEPS_DIR/root" -type d -path '*/lib/*/gstreamer-1.0' | head -1)"
BROWSERS="${PLAYWRIGHT_BROWSERS_PATH:-$HOME/.cache/ms-playwright}"
cat > "$DEPS_DIR/webkit-wrapper.sh" <<WRAP
#!/bin/sh
# Generated by scripts/setup-webkit-userland.sh - do not edit.
BUNDLE="\$(ls -d "$BROWSERS"/webkit-*/minibrowser-wpe 2>/dev/null | sort | tail -1)"
export WEBKIT_EXEC_PATH="\$BUNDLE/bin"
export WEBKIT_INJECTED_BUNDLE_PATH="\$BUNDLE/lib"
export WEBKIT_INSPECTOR_RESOURCES_PATH="\$BUNDLE/share"
export LD_LIBRARY_PATH="\$BUNDLE/lib:\$BUNDLE/sys/lib:${LIBDIRS%:}"
WEBKIT_FORCE_COMPLEX_TEXT=1 exec "\$BUNDLE/bin/MiniBrowser" "\$@"
WRAP
chmod +x "$DEPS_DIR/webkit-wrapper.sh"

echo
echo "Unpacked into: $DEPS_DIR"
echo "Launch wrapper (executable_path for the WebKit launch only): $DEPS_DIR/webkit-wrapper.sh"
echo "Env the engine fixture applies to the WebKit launch only:"
echo "  GST_PLUGIN_PATH=${GST_DIR}"
