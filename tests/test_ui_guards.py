def test_library_testid_patterns(tmp_path) -> None:
    """AC2: the two DD2 library patterns (literal, parametric)."""
    _write(tmp_path, "a.js", "App.ui.button({label: 'x', testid: 'x-save-btn'});\n")
    lit, par, _ = extract_testids(tmp_path)
    assert set(lit) == {"x-save-btn"} and par == {}

    _write(tmp_path, "a.js", "var o = {testid: 'x-row-' + a.id};\n")
    lit, par, _ = extract_testids(tmp_path)
    assert lit == {} and set(par) == {"x-row-"}

    _write(tmp_path, "a.js", "var o = {testid: 'x-row-'\n    + a.id};\n")
    lit, par, _ = extract_testids(tmp_path)
    assert lit == {} and set(par) == {"x-row-"}

    _write(tmp_path, "a.js", "var rows = [\n  {label: 'A', href: '#a', testid: 'x-item-a'},\n];\n")
    lit, par, _ = extract_testids(tmp_path)
    assert set(lit) == {"x-item-a"} and par == {}

    _write(tmp_path, "a.js", "var o = {rowtestid: 'nope'};\n")
    lit, par, _ = extract_testids(tmp_path)
    assert lit == {} and par == {}

    # M25 F4 L1: ``<lower>Testid`` option keys (searchList's inputTestid and
    # rowTestid) are registry-visible like ``testid``.
    _write(tmp_path, "a.js", "f({inputTestid: 'x-search', rowTestid: 'x-row-' + n});\n")
    lit, par, _ = extract_testids(tmp_path)
    assert set(lit) == {"x-search"} and set(par) == {"x-row-"}


