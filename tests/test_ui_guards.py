def _write(root, rel, text):
    f = root / rel
    f.parent.mkdir(parents=True, exist_ok=True)
    f.write_text(text)


def test_extractors_work_against_any_directory(tmp_path) -> None:
    """AC1: extract_testids/classify_sinks take paths relative to the dir scanned."""
    _write(tmp_path, "sub/a.js", "x.setAttribute('data-testid', 'a-btn');\nel.innerHTML = v;\n")
    literals, _, _ = extract_testids(tmp_path)
    assert literals == {"a-btn": {"sub/a.js"}}
    dynamic, static = classify_sinks(tmp_path)
