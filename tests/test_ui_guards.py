"""UI regression-net guards: testid registry sync + innerHTML sink freeze
+ design-token mirror sync.

Mission 17 Flight 1 ("Regression-Net Foundation") design decisions:

- **Testid registry sync** — ``docs/ui-testid-registry.md`` is the
  human-readable catalogue of every ``data-testid`` the UI defines.
  These tests extract the ids live from
  ``the_one/interfaces/web/static/js/**/*.js`` and diff them against the
  registry in both directions, failing with the exact add/remove list.
  Two id classes: literal ids and parametric prefix families (ids built
  by concatenation, registered by static prefix).  Variable-carried ids
  (invisible to extraction) live in the registry's manual-exceptions
  table; their continued presence as string literals is asserted here.
- **innerHTML baseline-freeze** — every *dynamic*
  ``.innerHTML``/``.outerHTML`` assignment and ``insertAdjacentHTML``
  call site existing at freeze time is recorded below
  (``DYNAMIC_SINK_BASELINE``).  The guard fails on any NEW dynamic sink
  site (snippet-level match per file, so an offsetting add+remove in the
  same file is still caught).  Static single-string-literal assignments
  (including ``= ''`` clears) are exempt.  Removing a site does NOT fail
  the guard — the allowlist ratchets down as later flights migrate files
  to the sanctioned sink (Flight 4 sanitizer chokepoint; Flight 7
  verifies the ratchet).  When a file's sites shrink, prune its baseline
  entries opportunistically.

Mission 17 Flight 2 ("Design Language v3") adds:

- **Design-token mirror sync** — ``tests/browser/design_tokens.py``
  mirrors every literal-hex palette token per theme block of
  ``tokens.css``.  The guard parses the CSS's two TOP-LEVEL theme blocks
  (@media redefinitions stripped first) and asserts, mirror-driven, that
  each mirror value matches its CSS definition (hex-normalized,
  case-insensitive).  Mirror-driven direction is deliberate: a
  CSS-driven completeness sweep would drag in badge/wash/indirection
  values the mirror deliberately omits (see the mirror module docstring
  for the omission rationale).

To update after intentional changes:

- New/renamed/removed testid → edit the matching registry table row.
- Removed a dynamic sink → optionally prune its snippet here.
- New dynamic sink → don't.  Render via ``createElement``/``textContent``
  or a static template instead; the freeze exists to stop growth.

Extraction logic lives in ``tests/_ui_guard_helpers.py`` (same genre as
``tests/test_token_definitions.py``: repo-source lint-by-pytest, plain
pytest + pathlib + re, no new dependencies).
"""

