def test_markdown_no_html_string_invariant() -> None:
    """``markdown.js`` must never build DOM from an HTML string.

    Two static assertions freeze the structural XSS guarantee (M17 F4 "No
    vendoring" DD):

    1. ZERO ``innerHTML``/``outerHTML``/``insertAdjacentHTML`` tokens (the
       three literal HTML-string sinks).
    2. Every ``createElement`` argument is a bare string literal OR one of the
       two proven-bounded dynamic-tag expressions (``'h' + lvl`` -> h1..h6,
       ``ordered ? 'ol' : 'ul'`` -> ol|ul). Any other non-literal arg fails.

    The ``render()``-returns-a-DocumentFragment leg of the invariant is
    asserted at runtime in ``tests/browser/test_markdown.py`` (see
    ``test_markdown_render_returns_document_fragment``). injectIcon()'s trusted
    ``DOMParser().parseFromString(svg, 'image/svg+xml')`` glyph path is the
    sanctioned no-inner-HTML seam and is deliberately NOT scanned here (see the
    allowance note in ``_ui_guard_helpers``).

    Fails naming the offending line so a reintroduced seam is obvious."""
    lines: list[str] = []

    sink_hits = find_markdown_html_sink_tokens()
    if sink_hits:
        lines.append(
            f"{MARKDOWN_JS.name} contains HTML-string sink token(s) — the no-inner-HTML "
            "invariant is broken (build DOM via createElement/textContent instead):"
        )
        lines.extend(f"  {MARKDOWN_JS.name}:{ln}: [{tok}] {src}" for ln, tok, src in sink_hits)

    bad_args = find_markdown_bad_create_element_args()
    if bad_args:
        allowed = ", ".join(sorted(MARKDOWN_DYNAMIC_CREATE_ELEMENT_ALLOWED))
        lines.append(
            f"{MARKDOWN_JS.name} has createElement call(s) with a non-literal, "
            f"non-allowlisted tag argument (allowed dynamic tags: {allowed}):"
        )
        lines.extend(f"  {MARKDOWN_JS.name}:{ln}: createElement({arg})" for ln, arg in bad_args)

    if lines:
        raise AssertionError("\n".join(lines))


def test_js_string_css_var_refs_are_defined() -> None:
    """Every ``var(--token)`` baked into a JS STRING literal must be defined in
    ``tokens.css`` or ``fonts.css`` (M17 F3 debrief rec 5 — the dead-alias-in-JS
    miss class). CSS treats an undefined custom property as ``unset`` (silent),
    and ``test_token_definitions.py`` only scans ``*.css`` — a ``var(--x)`` in a
    JS inline-style / innerHTML template is invisible to it. Comments are
    excluded from the scan (prose ``var(--x)`` mentions are not references).
    Fails naming the token and the file(s) that reference it."""
    dead = find_js_dead_css_var_refs()
    if dead:
        lines = [
            "Dead CSS-var reference(s) in JS string literals (token absent from",
            "tokens.css/fonts.css — CSS would silently render `unset`):",
        ]
        for token in sorted(dead):
            files = ", ".join(sorted(dead[token]))
            lines.append(f"  {token}  (referenced in: {files})")
        raise AssertionError("\n".join(lines))
